#!/usr/bin/env node
'use strict'

/**
 * grim-host.js — Homelab host management
 *
 * Subcommands:
 *   list                   List all KB-registered hosts (tag: hardware/inventory)
 *   gen-hosts [--out F]    Generate /etc/hosts block from KB network data
 *   gen-hosts --apply      Write managed block to /etc/hosts (needs sudo)
 *   sync-config [<host>]   Push ~/.config/lbl-configs/<host>.json to each host
 *   register               Run grim-register-host.sh on this machine
 *
 * Config sync layout:
 *   ~/.config/lbl-configs/<hostname>.json  — one per target host
 *   Syncs to: <host>:~/.config/lbl-config.json via SSH
 *
 * Entity source:
 *   Local mode — scans entity files directly (always fresh, no stale graph.json)
 *   Reads rig.json ($GRIMOIRE_ROOT/rig.json) for SSH host list in sync-config
 */

const fs       = require('node:fs')
const os       = require('node:os')
const path     = require('node:path')
const { exec, spawnSync } = require('node:child_process')
const minimist = require('minimist')
const { config } = require('../lib/env')

const HOSTS_BEGIN = '# BEGIN grimoire-hosts (managed by \'grim host gen-hosts --apply\' — do not edit)'
const HOSTS_END   = '# END grimoire-hosts'

// ── IP filtering helpers ──────────────────────────────────────────────────────

/**
 * Return true if an IP is link-local (169.254.x), loopback (127.x), or
 * otherwise unsuitable for /etc/hosts fleet resolution.
 */
function _isUsableIP(ip) {
  if (!ip) return false
  // Link-local
  if (ip.startsWith('169.254.')) return false
  // Loopback
  if (ip.startsWith('127.')) return false
  // IPv6 (we only handle IPv4 for /etc/hosts)
  if (ip.includes(':')) return false
  // Multicast / reserved
  if (ip.startsWith('224.') || ip.startsWith('240.')) return false
  return true
}

/**
 * Pick one canonical LAN IP from an address list.
 * Filters out link-local, loopback, non-LAN. Picks lowest IP deterministically.
 */
function _canonicalIP(addrs) {
  const usable = (addrs || [])
    .map(a => a.ip)
    .filter(_isUsableIP)
  if (!usable.length) return null
  // Sort by octet numerics for deterministic lowest-IP selection
  usable.sort((a, b) => {
    const pa = a.split('.').map(Number)
    const pb = b.split('.').map(Number)
    for (let i = 0; i < 4; i++) {
      if (pa[i] !== pb[i]) return pa[i] - pb[i]
    }
    return 0
  })
  return usable[0]
}


class GrimHost {

  // ── KB entity access ─────────────────────────────────────────────────────────
  // Scan entity files directly — avoids stale graph.json after fresh register

  _scanEntities() {
    if (!config.root) throw new Error('GRIMOIRE_ROOT not set — local KB required')
    const entitiesDir = path.join(config.root, 'entities')
    if (!fs.existsSync(entitiesDir)) throw new Error(`Entities dir not found: ${entitiesDir}`)

    const results = []
    const walk = dir => {
      for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name)
        if (entry.isDirectory()) { walk(full); continue }
        if (!entry.name.endsWith('.json')) continue
        try {
          const e = JSON.parse(fs.readFileSync(full, 'utf8'))
          if ((e.tags || []).includes('hardware/inventory')) results.push(e)
        } catch { /* skip malformed */ }
      }
    }
    walk(entitiesDir)
    return results
  }

  // ── list ──────────────────────────────────────────────────────────────────────

  async list() {
    const hosts = this._scanEntities()
    if (!hosts.length) {
      console.log('No registered hosts. Run: grim host register')
      return
    }
    const W = 12
    console.log(`\n  ${'HOST'.padEnd(W)}  ${'IP'.padEnd(16)}  DESCRIPTION\n`)
    for (const h of hosts.sort((a, b) => a.name.localeCompare(b.name))) {
      const ip = _canonicalIP(h.network?.addresses) || '—'
      console.log(`  ${(h.name || '?').padEnd(W)}  ${ip.padEnd(16)}  ${h.description || ''}`)
    }
    console.log()
  }

  // ── gen-hosts ─────────────────────────────────────────────────────────────────

  /**
   * Generate /etc/hosts lines from KB entities.
   * One canonical LAN IP per host; link-local and dupes dropped.
   */
  async genHosts({ out, apply } = {}) {
    const hosts = this._scanEntities()
    if (!hosts.length) {
      console.error('No registered hosts in KB. Run: grim host register')
      process.exit(1)
    }

    const lines = [
      '# Generated by: grim host gen-hosts',
      `# Date: ${new Date().toISOString()}`,
    ]

    for (const h of hosts.sort((a, b) => a.name.localeCompare(b.name))) {
      const ip = _canonicalIP(h.network?.addresses)
      if (!ip) {
        lines.push(`# ${h.name}: no usable IP recorded`)
        continue
      }
      lines.push(`${ip.padEnd(20)} ${h.name}`)
    }
    lines.push('')
    const output = lines.join('\n')

    if (apply) {
      await this._applyHosts(output)
      console.log(`Wrote managed block to /etc/hosts (${hosts.length} host(s))`)
    } else if (out) {
      fs.writeFileSync(out, output)
      console.log(`Wrote ${hosts.length} host(s) to ${out}`)
      console.log(`Apply with:  sudo cp ${out} /etc/hosts`)
    } else {
      process.stdout.write(output)
    }
  }

  /**
   * Idempotently replace the managed block in /etc/hosts.
   * If no existing block, appends before the first non-comment, non-empty line
   * after the header area. Never touches lines outside markers.
   */
  async _applyHosts(newBlock) {
    const hostsPath = '/etc/hosts'
    let current = ''
    try {
      current = fs.readFileSync(hostsPath, 'utf8')
    } catch {
      console.error('Cannot read /etc/hosts — run with sudo?')
      process.exit(1)
    }

    const beginIdx = current.indexOf(HOSTS_BEGIN)
    const endIdx   = current.indexOf(HOSTS_END)

    // Strip trailing blank lines from newBlock so we don't double-newline at
    // the boundary with surrounding text.
    const cleanBlock = (HOSTS_BEGIN + '\n' + newBlock.trimEnd() + '\n' + HOSTS_END).trimEnd()

    let updated
    if (beginIdx !== -1 && endIdx !== -1) {
      // Replace existing block
      const after = current.slice(endIdx + HOSTS_END.length)
      updated = current.slice(0, beginIdx) + cleanBlock + (after.startsWith('\n') ? after : '\n' + after)
    } else {
      // Append block before first substantive line (skip leading comments/blanks)
      const firstContent = current.search(/[^\s#]/)
      if (firstContent === -1) {
        // Empty file or all comments — append
        updated = current + '\n' + cleanBlock
      } else {
        // Insert before first content line
        updated = current.slice(0, firstContent) + '\n' + cleanBlock + current.slice(firstContent)
      }
    }

    // Write back
    const { execSync } = require('node:child_process')
    if (process.getuid() !== 0) {
      // Not root — use sudo
      const tmp = require('os').tmpdir() + '/grim-hosts-tmp-' + process.pid
      fs.writeFileSync(tmp, updated)
      try {
        execSync(`sudo cp "${tmp}" ${hostsPath}`, { stdio: 'inherit' })
      } finally {
        try { fs.unlinkSync(tmp) } catch (_) {}
      }
    } else {
      fs.writeFileSync(hostsPath, updated)
    }
  }

  // ── sync-config ───────────────────────────────────────────────────────────────
  // lbl-config.json is identical across all hosts — same topology, same endpoint
  // names (resolved via /etc/hosts). Source is always the local copy; push to
  // every non-local, non-skip host in rig.json.

  async syncConfig({ hostname } = {}) {
    const srcPath = path.join(os.homedir(), '.config', 'lbl-config.json')
    if (!fs.existsSync(srcPath)) {
      console.error(`Source not found: ${srcPath}`)
      process.exit(1)
    }

    const rig = this._loadRig()
    if (!rig.length) {
      console.error(`No hosts in rig.json ($GRIMOIRE_ROOT/rig.json)`)
      process.exit(1)
    }

    const localHost = os.hostname().toLowerCase()
    const targets = rig.filter(b => {
      if (b.skip) return false
      if ((b.aliases || []).some(a => a === localHost)) return false  // skip self
      if (hostname && b.host !== hostname && b.label !== hostname) return false
      return true
    })

    if (!targets.length) {
      console.error(hostname ? `Host '${hostname}' not found in rig.json (or is local)` : 'No remote hosts to sync')
      process.exit(1)
    }

    const content = fs.readFileSync(srcPath, 'utf8')
    let ok = 0, failed = 0

    for (const box of targets) {
      const success = await this._sshWrite(box.host, content)
      if (success) { console.log(`  ✔  ${box.host}`); ok++ }
      else         { console.warn(`  ✗  ${box.host}  SSH failed`); failed++ }
    }

    console.log(`\n  ${ok} synced · ${failed} failed`)
    if (failed) process.exit(1)
  }

  _sshWrite(host, content) {
    return new Promise(resolve => {
      const { execFile } = require('node:child_process')
      const proc = execFile('ssh', [
        '-o', 'BatchMode=yes',
        '-o', 'ConnectTimeout=8',
        '-o', 'StrictHostKeyChecking=accept-new',
        host,
        'mkdir -p ~/.config && cat > ~/.config/lbl-config.json',
      ], { timeout: 15000 }, err => resolve(!err))
      proc.stdin.end(content)
    })
  }

  // ── register ──────────────────────────────────────────────────────────────────

  register() {
    const script = path.join(__dirname, '..', 'deploy', 'grim-register-host.sh')
    if (!fs.existsSync(script)) {
      console.error(`Script not found: ${script}`)
      process.exit(1)
    }
    const r = spawnSync('bash', [script], { stdio: 'inherit', env: process.env })
    process.exit(r.status ?? 0)
  }

  // ── helpers ───────────────────────────────────────────────────────────────────

  _loadRig() {
    const rigPath = config.root ? path.join(config.root, 'rig.json') : null
    if (!rigPath || !fs.existsSync(rigPath)) return []
    try { return JSON.parse(fs.readFileSync(rigPath, 'utf8')) }
    catch { return [] }
  }

  // ── CLI ───────────────────────────────────────────────────────────────────────

  async main() {
    const args = minimist(process.argv.slice(3), {
      string:  ['out', 'host'],
      boolean: ['help', 'apply'],
      alias:   { h: 'help', o: 'out' },
    })

    const sub = args._[0] || 'list'

    if (args.help || sub === 'help') {
      console.log(`
  Usage: grim host <subcommand> [options]

  Subcommands:
    list                    List all registered hosts from KB
    gen-hosts [--out F]     Generate /etc/hosts entries for all registered hosts
    gen-hosts --apply       Write managed block to /etc/hosts (needs sudo)
    sync-config [<host>]    Push per-host lbl-config to each host
    register                Inventory this machine and register it in the KB

  Options for gen-hosts:
    --out <file>    Write to file instead of stdout
    --apply         Write managed block to /etc/hosts (requires sudo)

  Managed block:
    Lines between # BEGIN grimoire-hosts and # END grimoire-hosts are
    fully replaced on each --apply. Lines outside the markers are untouched.

  Config sync:
    Source:  ~/.config/lbl-config.json  (local machine — source of truth)
    Dest:    <host>:~/.config/lbl-config.json via SSH (same file, all hosts)
    Skips:   local machine, skip:true hosts in rig.json

  Examples:
    grim host list
    grim host gen-hosts
    grim host gen-hosts --out /tmp/grim-hosts && sudo cp /tmp/grim-hosts /etc/hosts
    grim host gen-hosts --apply
    grim host sync-config <host>
    grim host sync-config
`)
      return
    }

    if (sub === 'list')          return this.list()
    if (sub === 'gen-hosts')     return this.genHosts({ out: args.out, apply: args.apply })
    if (sub === 'register')      return this.register()
    if (sub === 'sync-config') {
      const hostname = args._[1] || args.host || null
      return this.syncConfig({ hostname })
    }

    console.error(`grim host: unknown subcommand '${sub}'`)
    console.error(`Run 'grim host --help'`)
    process.exit(1)
  }
}

if (require.main === module) {
  new GrimHost().main().catch(e => { console.error(e.message); process.exit(1) })
}

module.exports = { GrimHost, _canonicalIP, _isUsableIP, HOSTS_BEGIN, HOSTS_END }
